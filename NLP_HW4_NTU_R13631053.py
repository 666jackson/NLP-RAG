    # TODO4-3: Run the RAG system
    response = chain.invoke({"input": query})

    generated_answer = response["answer"]
    retrieved_docs = response["context"] # 這是抓回來的 document chunks
    ground_truth = answers[i]

    # --- 評估 Evaluation ---

    # 1. 計算 Accuracy (生成準確度)
    # 判斷標準：如果正確答案 (ground_truth) 出現在生成的回答中，視為正確
    is_correct = ground_truth.lower() in generated_answer.lower()
    if is_correct:
        correct_predictions += 1

    # 2. 計算 Recall@k (檢索召回率)
    # 判斷標準：正確答案是否包含在檢索回來的文本片段中

    # Recall@1: 檢查第一篇檢索到的文件
    if len(retrieved_docs) > 0:
        if ground_truth.lower() in retrieved_docs[0].page_content.lower():
            recall_at_1 += 1

    # Recall@5: 檢查前五篇檢索到的文件
    found_in_top_5 = False
    for doc in retrieved_docs[:5]:
        if ground_truth.lower() in doc.page_content.lower():
            found_in_top_5 = True
            break
    if found_in_top_5:
        recall_at_5 += 1

    # 收集資料準備寫入 JSON
    results_data.append({
        "id": i,
        "question": query,
        "ground_truth": ground_truth,
        "generated_answer": generated_answer,
        "correct": is_correct,
        "retrieved_docs": [doc.page_content for doc in retrieved_docs]
    })

