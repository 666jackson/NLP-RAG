"""## Recall用Index 去判斷"""

import json
from tqdm import tqdm


results_data = []
correct_predictions = 0
recall_at_1 = 0
recall_at_5 = 0


for i, query in tqdm(enumerate(queries), total=len(queries)):

    # ---- RAG 推論 ----
    response = chain.invoke({"input": query})

    generated_answer = response["answer"]
    retrieved_docs = response["context"]
    ground_truth = answers[i]

    # ==========================
    # Accuracy (文字包含)
    # ==========================
    is_correct = ground_truth.lower() in generated_answer.lower()
    if is_correct:
        correct_predictions += 1


    # ==========================
    # Recall（純順序比對）
    # ==========================

    # 正確 document index 就是題目 index i
    gt_index = i

    # Retriever 回來的 documents index
    retrieved_indices = [
        doc.metadata["id"]
        for doc in retrieved_docs[:5]
        if "id" in doc.metadata
    ]


    # Recall@1
    if len(retrieved_indices) > 0 and retrieved_indices[0] == gt_index:
        recall_at_1 += 1

    # Recall@5
    if gt_index in retrieved_indices:
        recall_at_5 += 1


    # ==========================
    # Store results
    # ==========================

    results_data.append({
        "id": i,
        "question": query,
        "ground_truth": ground_truth,
        "generated_answer": generated_answer,
        "correct": is_correct,
        "ground_truth_index": gt_index,
        "retrieved_indices": retrieved_indices,
        "retrieved_docs": [doc.page_content for doc in retrieved_docs],
    })


# ==========================
# Output scores
# ==========================

total = len(queries)

accuracy_score = correct_predictions / total
r1_score = recall_at_1 / total
r5_score = recall_at_5 / total

print("\n===== RAG Evaluation Results (Index-based, sequential GT) =====")
print(f"Accuracy:  {accuracy_score:.2%}")
print(f"Recall@1:  {r1_score:.2%}")
print(f"Recall@5:  {r5_score:.2%}")


# ==========================
# Save JSON
# ==========================

output_file = "rag_evaluation_results_index.json"

with open(output_file, "w", encoding="utf-8") as f:
    json.dump(results_data, f, ensure_ascii=False, indent=4)

print(f"\nResults saved to {output_file}")